export function measureWord(word: string): number {
  let w = 0;
  for (const ch of word.toUpperCase()) {
    const g = GLYPHS[ch] ?? GLYPHS[" "];
    w += g[0].length;
  }
  return w;
}

export function writeGlyphs(
  put: (col: number, row: number, ch: string) => void,
  word: string,
  col: number,
  row: number,
) {
  let x = col;
  for (const ch of word.toUpperCase()) {
    const glyph = GLYPHS[ch] ?? GLYPHS[" "];
    for (let r = 0; r < GLYPH_H; r++) {
      const line = glyph[r];
      for (let c = 0; c < line.length; c++) {
        const gc = line[c];
        if (gc !== " ") put(x + c, row + r, gc);
      }
    }
    x += glyph[0].length;
  }
}
